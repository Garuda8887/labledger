"""Twelve+ distinct fictional lab report layouts. Names are invented — not real brands."""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Literal


ColumnKey = Literal["test", "result", "unit", "ref", "flag", "method"]


@dataclass
class LayoutSpec:
    id: str
    lab_name: str
    description: str
    columns: list[ColumnKey]
    header_labels: dict[str, str]
    features: list[str] = field(default_factory=list)
    multi_column: bool = False
    multi_page: bool = False
    section_headers: bool = True
    clutter: bool = False
    wrap_refs: bool = False
    method_col: bool = False
    flag_col: bool = False
    sex_specific: bool = False
    indian_units: bool = False
    comparators: bool = False
    qualitative: bool = False
    mixed_si: bool = False
    page_break_after_sections: list[str] = field(default_factory=list)
    footer_lines: list[str] = field(default_factory=list)
    header_extra: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "lab_name": self.lab_name,
            "description": self.description,
            "columns": list(self.columns),
            "features": list(self.features),
        }


